use fsend_proto::{
    code::{Code, CodeError},
    rendezvous::{self, Action},
};
use serde::Serialize;
use wasm_bindgen::prelude::*;

#[derive(Serialize)]
#[cfg_attr(test, derive(ts_rs::TS))]
#[serde(untagged)]
enum ParsedCode {
    Valid { code: String },
    Invalid { error: CodeError, message: String },
}

/// Parses a code into a [`ParsedCode`].
#[wasm_bindgen(js_name = parseCode)]
pub fn parse_code(input: &str) -> String {
    let parsed = match input.parse::<Code>() {
        Ok(code) => ParsedCode::Valid {
            code: code.to_string(),
        },
        Err(error) => ParsedCode::Invalid {
            message: error.to_string(),
            error,
        },
    };
    serde_json::to_string(&parsed).expect("parsed codes serialize")
}

#[wasm_bindgen(js_name = codeLink)]
pub fn code_link(site: &str, code: &str) -> Result<String, JsError> {
    Ok(code.parse::<Code>()?.link(site))
}

#[wasm_bindgen]
pub struct Rendezvous(rendezvous::Rendezvous);

#[wasm_bindgen]
impl Rendezvous {
    /// `transports` is a JSON `Transport[]`.
    pub fn sender(transports: &str, app: &str) -> Result<Rendezvous, JsError> {
        Ok(Self(rendezvous::Rendezvous::sender(
            serde_json::from_str(transports)?,
            app,
        )))
    }

    pub fn receiver(code: &str, transports: &str, app: &str) -> Result<Rendezvous, JsError> {
        Ok(Self(rendezvous::Rendezvous::receiver(
            &code.parse()?,
            serde_json::from_str(transports)?,
            app,
        )))
    }

    pub fn text(&mut self, frame: &str) {
        self.0.text(frame);
    }

    pub fn binary(&mut self, frame: &[u8]) {
        self.0.binary(frame);
    }

    pub fn closed(&mut self) {
        self.0.closed();
    }

    /// `message` is a JSON `Sealed`.
    #[wasm_bindgen(js_name = sendSealed)]
    pub fn send_sealed(&mut self, message: &str) -> Result<(), JsError> {
        self.0.send_sealed(serde_json::from_str(message)?);
        Ok(())
    }

    /// The next action, if any: a binary frame for the relay as a
    /// `Uint8Array`, any other action as a JSON `Action`.
    pub fn poll(&mut self) -> Option<JsValue> {
        Some(match self.0.poll()? {
            Action::SendBinary { data } => data.into(),
            action => serde_json::to_string(&action)
                .expect("actions serialize")
                .into(),
        })
    }
}

#[cfg(test)]
mod bindings {
    use std::{env, fs, path::Path};

    use fsend_proto::{
        pairing::{ConnectionInfo, Sealed},
        relay::{ErrorCode, Transport},
        rendezvous::{Action, Event, RendezvousError},
    };
    use ts_rs::{Config, TS};

    use super::*;

    const OUT: &str = "../fsend-site/src/lib/proto/generated/protocol.ts";

    #[test]
    fn typescript_bindings_are_fresh() {
        let cfg = Config::new().with_large_int("number");
        let decls = [
            Action::decl(&cfg),
            Event::decl(&cfg),
            RendezvousError::decl(&cfg),
            ErrorCode::decl(&cfg),
            Transport::decl(&cfg),
            Sealed::decl(&cfg),
            ConnectionInfo::decl(&cfg),
            ParsedCode::decl(&cfg),
            CodeError::decl(&cfg),
        ];
        let header = format!(
            "// Generated by `cargo test -p fsend-proto-wasm`. Do not edit.\n\n\
             export const CODE_LENGTH = {};\n",
            fsend_proto::code::CODE_LEN
        );
        let expected = decls
            .iter()
            .fold(header, |out, decl| out + "\nexport " + decl + "\n");

        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join(OUT);
        if env::var_os("UPDATE_BINDINGS").is_some() {
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(&path, &expected).unwrap();
        }
        let actual = fs::read_to_string(&path).unwrap_or_default();
        assert!(
            actual == expected,
            "{OUT} is stale; regenerate it with `UPDATE_BINDINGS=1 cargo test -p fsend-proto-wasm`"
        );
    }
}
